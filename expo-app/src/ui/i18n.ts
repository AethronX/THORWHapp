/** Arabic CLDR plural categories. */
function arPlural(n: number, f: { zero: string; one: string; two: string; few: string; many: string; other: string }) {
  if (n === 0) return f.zero;
  if (n === 1) return f.one;
  if (n === 2) return f.two;
  const m = n % 100;
  if (m >= 3 && m <= 10) return f.few;
  if (m >= 11 && m <= 99) return f.many;
  return f.other;
}

/** "3 أيام" / "11 يومًا" / "يومين" … */
function arDays(n: number) {
  return arPlural(n, { zero: '0 يوم', one: 'يوم واحد', two: 'يومين', few: `${n} أيام`, many: `${n} يومًا`, other: `${n} يوم` });
}

/** "شهر واحد" / "شهرين" / "3 أشهر" / "11 شهرًا" */
function arMonthsCount(n: number) {
  return arPlural(n, { zero: '0 شهر', one: 'شهر واحد', two: 'شهرين', few: `${n} أشهر`, many: `${n} شهرًا`, other: `${n} شهر` });
}

